/**
 * Build-time generator for the talk summaries every page but the talk record
 * renders.
 *
 * Why: `src/lib/data/communications` is ~220 KiB of record data, 46% of it
 * `abstract`, and the built chunk sat in the static import graph of nine
 * routes — /cv/timeline, /conference-activity and its slides and
 * visualisations pages, /communications/[id], the five research projects and
 * /style-guide — plus four CV components. Only the talk record page prints an
 * abstract; the bibliography row prints 180 characters of it and nothing else
 * touches it. This script projects each record down to what a list row, a CV
 * entry, a timeline card or a facet needs and emits a static literal module;
 * the talk page keeps importing the full record.
 *
 * The projection keeps every `Communication` field except the heavy one
 * (HEAVY_COMMUNICATION_FIELDS) and adds what the rows derive from it:
 *   - `abstractExcerpt`: the abstract's first ABSTRACT_EXCERPT_LENGTH + 1
 *     characters — one more than the longest truncation a row applies, so
 *     `truncateAbstract(excerpt, n)` equals `truncateAbstract(abstract, n)`
 *     for every n up to that length, ellipsis included (summaries.test.ts
 *     enforces it).
 *
 * `papers` is deliberately kept: the conference visualisations build the
 * co-presenter and institution networks out of `papers[].authors`, so it has a
 * consumer outside the record page.
 *
 * Ordering: records are emitted in source-path order rather than id order,
 * because that is the order Vite's `import.meta.glob` hands the full index.
 * `sortByDate` is stable, so two talks sharing a date keep their input order —
 * emitting ids instead would silently swap such a pair between the index and
 * the projection. summaries.test.ts asserts the two orders are identical.
 *
 * How: the data files are loaded straight from TypeScript by the shared
 * loader in scripts/lib/data-records.mjs. Runs automatically via the npm
 * `prebuild` hook, or manually with `npm run gen:summaries` (which regenerates
 * the publication summaries in the same breath). Output is deterministic.
 *
 * Modes:
 *   node scripts/generate-communication-summaries.mjs          # (re)write
 *   node scripts/generate-communication-summaries.mjs --check  # CI freshness
 *       check: regenerate in memory and exit 1 if the committed file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { collectRecords } from './lib/data-records.mjs';
import { ABSTRACT_EXCERPT_LENGTH } from '../src/lib/data/publications/summaryConfig.ts';
import { HEAVY_COMMUNICATION_FIELDS } from '../src/lib/data/communications/summaryConfig.ts';

const DATA_DIR = 'src/lib/data/communications';
const OUT_FILE = `${DATA_DIR}/summaries.generated.ts`;
const CHECK_MODE = process.argv.includes('--check');

/** Project a full record down to its summary. */
function summarise(record) {
	const summary = {};
	for (const [key, value] of Object.entries(record)) {
		if (!HEAVY_COMMUNICATION_FIELDS.includes(key)) summary[key] = value;
	}
	if (typeof record.abstract === 'string' && record.abstract.length > 0) {
		// One character past the contract length: an abstract that continues
		// beyond it stays longer than any permitted truncation, so the row's
		// truncation still appends its ellipsis.
		const keep = ABSTRACT_EXCERPT_LENGTH + 1;
		summary.abstractExcerpt =
			record.abstract.length <= keep ? record.abstract : record.abstract.slice(0, keep);
	}
	return summary;
}

/** The glob key Vite sorts by: the path under DATA_DIR, forward slashes. */
function globKey(file) {
	return relative(DATA_DIR, file).split(/[\\/]/).join('/');
}

const records = await collectRecords(`${DATA_DIR}/**/*.ts`, 'gen:summaries:talks');
const summaries = records
	.map(({ file, record }) => ({ key: globKey(file), summary: summarise(record) }))
	.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0))
	.map(({ summary }) => summary);

const banner = `// AUTO-GENERATED by scripts/generate-communication-summaries.mjs — DO NOT EDIT.
// Regenerate with \`npm run gen:summaries\` (runs automatically via the prebuild hook).
/* eslint-disable */
import type { CommunicationSummary } from '$lib/types/communication';
export const communicationSummaries: CommunicationSummary[] = `;
const output = banner + JSON.stringify(summaries, null, '\t') + ';\n';

if (CHECK_MODE) {
	let committed = null;
	try {
		committed = readFileSync(OUT_FILE, 'utf8');
	} catch {
		// Missing file counts as stale.
	}
	if (committed !== output) {
		console.error(
			`[gen:summaries:talks] ERROR: ${OUT_FILE} is stale (or missing). ` +
				'Run `npm run gen:summaries` and commit the result.'
		);
		process.exit(1);
	}
	console.log(
		`[gen:summaries:talks] --check OK: ${OUT_FILE} is up to date (${summaries.length} summaries).`
	);
} else {
	writeFileSync(OUT_FILE, output, 'utf8');
	console.log(`[gen:summaries:talks] Wrote ${summaries.length} summaries → ${OUT_FILE}`);
}
