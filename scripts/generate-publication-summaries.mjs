/**
 * Build-time generator for the publication summaries the list pages render.
 *
 * Why: /publications, /cv and every research-project page imported the full
 * `allPublications` dataset — ~150 KB of JavaScript, ~48 KB on the wire — of
 * which the two heaviest fields, `citedBy` (40% of the bytes) and `abstract`
 * (23%), those pages never render. `citedBy` also grows with every citation
 * the monthly watcher records, so the dataset was set to get heavier for
 * pages that only tally it. This script projects each record down to what a
 * list row, a CV entry or a facet needs and emits a static literal module;
 * the publication page keeps importing the full record.
 *
 * The projection keeps every `Publication` field except the heavy four
 * (HEAVY_PUBLICATION_FIELDS) and adds what the list pages derive from them:
 *   - `abstractExcerpt`: the abstract's first ABSTRACT_EXCERPT_LENGTH + 1
 *     characters — one more than the longest truncation a row applies, so
 *     `truncateAbstract(excerpt, n)` equals `truncateAbstract(abstract, n)`
 *     for every n up to that length, ellipsis included (summaries.test.ts
 *     enforces it).
 *   - `citedByCount`: the tally the rows print and the citations sort uses.
 *   - `tocAuthors`: contributor names from the table of contents, which the
 *     authors facet counts and matches.
 *   - `sourceDirType`: the directory-derived type the full index also adds.
 *
 * How: the data files are loaded straight from TypeScript by the shared
 * loader in scripts/lib/data-records.mjs. Runs automatically via the npm
 * `prebuild` hook, or manually with `npm run gen:summaries`. Output is
 * deterministic (records sorted by id, keys in authored order).
 *
 * Modes:
 *   node scripts/generate-publication-summaries.mjs          # (re)write
 *   node scripts/generate-publication-summaries.mjs --check  # CI freshness
 *       check: regenerate in memory and exit 1 if the committed file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { collectRecords } from './lib/data-records.mjs';
import {
	ABSTRACT_EXCERPT_LENGTH,
	HEAVY_PUBLICATION_FIELDS
} from '../src/lib/data/publications/summaryConfig.ts';

const DATA_DIR = 'src/lib/data/publications';
const OUT_FILE = `${DATA_DIR}/summaries.generated.ts`;
const CHECK_MODE = process.argv.includes('--check');

/**
 * Directory → `sourceDirType`.
 *
 * !! KEEP IN SYNC with `dirTypeMap` in src/lib/data/publications/index.ts
 * (summaries.test.ts fails if the two disagree for any record).
 */
const DIR_TYPES = {
	books: 'books',
	articles: 'articles',
	bulletins: 'bulletins',
	chapters: 'chapters',
	'special-issues': 'specialIssues',
	reports: 'reports',
	encyclopedia: 'encyclopedia',
	blogposts: 'blogposts',
	dissertations: 'dissertations',
	proceedings: 'proceedings',
	'working-papers': 'workingPapers'
};

/** Unique contributor names from a table of contents, in order of appearance. */
function tocAuthors(tableOfContents) {
	const names = [];
	for (const entry of tableOfContents ?? []) {
		if (typeof entry === 'string') continue;
		for (const name of entry.authors ?? []) if (!names.includes(name)) names.push(name);
	}
	return names;
}

/** Project a full record down to its summary. */
function summarise(record, file) {
	const summary = {};
	for (const [key, value] of Object.entries(record)) {
		if (!HEAVY_PUBLICATION_FIELDS.includes(key)) summary[key] = value;
	}
	if (typeof record.abstract === 'string' && record.abstract.length > 0) {
		// One character past the contract length: an abstract that continues
		// beyond it stays longer than any permitted truncation, so the row's
		// truncation still appends its ellipsis.
		const keep = ABSTRACT_EXCERPT_LENGTH + 1;
		summary.abstractExcerpt =
			record.abstract.length <= keep ? record.abstract : record.abstract.slice(0, keep);
	}
	summary.citedByCount = Array.isArray(record.citedBy) ? record.citedBy.length : 0;
	summary.tocAuthors = tocAuthors(record.tableOfContents);
	const dir = relative(DATA_DIR, file).split(/[\\/]/)[0];
	summary.sourceDirType = DIR_TYPES[dir] ?? 'unknown';
	return summary;
}

const records = await collectRecords(`${DATA_DIR}/**/*.ts`, 'gen:summaries');
const summaries = records
	.map(({ file, record }) => summarise(record, file))
	.sort((a, b) => a.id.localeCompare(b.id));

const banner = `// AUTO-GENERATED by scripts/generate-publication-summaries.mjs — DO NOT EDIT.
// Regenerate with \`npm run gen:summaries\` (runs automatically via the prebuild hook).
/* eslint-disable */
import type { PublicationSummary } from '$lib/types/publication';
export const publicationSummaries: PublicationSummary[] = `;
const output = banner + JSON.stringify(summaries, null, '\t') + ';\n';

if (CHECK_MODE) {
	let committed = null;
	try {
		committed = readFileSync(OUT_FILE, 'utf8');
	} catch {
		// Missing file counts as stale.
	}
	if (committed !== output) {
		console.error(
			`[gen:summaries] ERROR: ${OUT_FILE} is stale (or missing). ` +
				'Run `npm run gen:summaries` and commit the result.'
		);
		process.exit(1);
	}
	console.log(
		`[gen:summaries] --check OK: ${OUT_FILE} is up to date (${summaries.length} summaries).`
	);
} else {
	writeFileSync(OUT_FILE, output, 'utf8');
	console.log(`[gen:summaries] Wrote ${summaries.length} summaries → ${OUT_FILE}`);
}
