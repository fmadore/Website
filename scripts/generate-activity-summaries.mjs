/**
 * Build-time generator for the activity summaries every page but the activity
 * record renders.
 *
 * Why: `src/lib/data/activities` is ~107 KiB of record data, 60% of it the
 * `content` HTML body only /activities/[id] prints, and the whole dataset sat
 * in the static import graph of /activities, its year pages and the style
 * guide. This projects each record down to what a log row or a facet needs —
 * every field except HEAVY_ACTIVITY_FIELDS — and emits a static literal module.
 * The record page reads the full record through its server load.
 *
 * Ordering: records are emitted in source-path order, the order Vite's
 * `import.meta.glob` hands the full index, so `sortByDate` (stable) orders the
 * two identically. summaries.test.ts asserts it.
 *
 * Modes:
 *   node scripts/generate-activity-summaries.mjs          # (re)write
 *   node scripts/generate-activity-summaries.mjs --check  # CI freshness
 *       check: regenerate in memory and exit 1 if the committed file is stale.
 */
import { collectRecords } from './lib/data-records.mjs';
import { CHECK_MODE, emitGenerated } from './lib/generated-file.mjs';
import { inGlobOrder, projectSummary } from './lib/summary-projection.mjs';
import { HEAVY_ACTIVITY_FIELDS } from '../src/lib/data/activities/summaryConfig.ts';

const DATA_DIR = 'src/lib/data/activities';
const OUT_FILE = `${DATA_DIR}/summaries.generated.ts`;

const records = await collectRecords(`${DATA_DIR}/*.ts`, 'gen:summaries:activities');
const summaries = inGlobOrder(records, DATA_DIR).map(({ record }) =>
	projectSummary(record, HEAVY_ACTIVITY_FIELDS)
);

const banner = `// AUTO-GENERATED by scripts/generate-activity-summaries.mjs — DO NOT EDIT.
// Regenerate with \`npm run gen:summaries\` (runs automatically via the prebuild hook).
/* eslint-disable */
import type { ActivitySummary } from '$lib/types/activity';
export const activitySummaries: ActivitySummary[] = `;
const output = banner + JSON.stringify(summaries, null, '\t') + ';\n';

if (
	!emitGenerated([[OUT_FILE, output]], {
		tag: 'gen:summaries:activities',
		command: 'npm run gen:summaries'
	})
)
	process.exit(1);
console.log(
	CHECK_MODE
		? `[gen:summaries:activities] --check OK: ${OUT_FILE} is up to date (${summaries.length} summaries).`
		: `[gen:summaries:activities] Wrote ${summaries.length} summaries → ${OUT_FILE}`
);
